def r_zone(no):
    """查 R 号落在哪个权限区。返回 dict 或 None(未定义区)。"""
    for lo, hi, rd, wr, bit, keep, note in R_ZONES:
        if lo <= no <= hi:
            return {"lo": lo, "hi": hi, "read": rd, "write": wr,
                    "bit": bit, "keep": keep, "note": note}
    return None


