def build_reverse_index():
    idx = {}
    def add(addr, meaning):
        if addr:
            idx.setdefault(addr, []).append(meaning)
    for name, info in AXIAL.items():
        t = info["type"]
        for ax, a in enumerate(info["axes"], start=1):
            add(a, f"[{t}] {name} (轴{ax})")
        for ax, al in info.get("alias", {}).items():
            add(al, f"[{t}] {name} (轴{ax}) alias")
    for name, info in MST.items():
        t = info["type"]
        for ch, a in info["ch"].items():
            add(a, f"[{t}] {name} (通道{ch})")
    for a, m in GENERAL.items():
        add(a, m)
    return idx


REVERSE_INDEX = build_reverse_index()


def lookup(addr):
    """查询一个地址的标准含义。"""
    return REVERSE_INDEX.get(addr, [])


